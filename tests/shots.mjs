// Takes a picture of every screen at phone size so the design can be checked by eye.   node tests/shots.mjs   (app on :8123)
import { chromium } from '/opt/node-tools/node_modules/playwright/index.mjs';
const URL = process.env.URL || 'http://localhost:8123/';
const OUT = process.env.OUT || '/tmp/s/shots';
const CAM = process.env.FAKECAM ? [`--use-file-for-fake-video-capture=${process.env.FAKECAM}`] : [];
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream', ...CAM] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, permissions: ['camera', 'microphone'] });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => { errs.push(e.message); console.log('PAGE ERROR:', e.message); });
p.on('console', (m) => { if (m.type() === 'error' && !/404/.test(m.text())) console.log('console error:', m.text().slice(0, 140)); });
await p.addInitScript(() => { window.__DEMO_AUTH = true; });
const shot = async (name, wait = 500) => { await p.waitForTimeout(wait); await p.screenshot({ path: `${OUT}/${name}.png` }); };
await p.goto(URL); await p.waitForTimeout(1200);
await shot('01-welcome');
await p.click('text=Start my album'); await shot('02-signin');
await p.fill('.signin input[type=email]', 'anushka@example.com'); await p.click('text=Email me a code'); await p.waitForTimeout(400);
await p.fill('.code-input', '1234'); await shot('03-code');
await p.fill('.code-input', '123456'); await p.waitForTimeout(900);
await shot('04-terms');
await p.click('.check'); await p.click('text=Start my free week'); await p.waitForTimeout(600);
await shot('05-intro1'); await p.click('text=Next'); await shot('06-intro2'); await p.click('text=Next'); await shot('07-intro3');
await p.click('text=Let’s begin'); await shot('08-home', 900);
await p.evaluate(() => window.scrollTo(0, 99999)); await shot('08b-home-scrolled', 300);
await p.evaluate(() => window.__lt.go('calendar', {}, { replace: true })); await shot('09-calendar', 800);
const info = await p.evaluate(() => { const t = window.__lt.store.tales.filter((x) => !x.sample)[0] || window.__lt.store.tales[0]; const dates = [...new Set(window.__lt.store.tales.map((x) => x.date))].sort(); return { id: t.id, date: t.date, dates }; });
await p.evaluate((d) => window.__lt.go('day', { date: d }), info.date); await shot('10-day', 900);
await p.evaluate((i) => window.__lt.go('tale', { id: i }), info.id); await shot('11-tale', 1200);
await p.evaluate(() => window.__lt.go('account', {}, { replace: true })); await shot('12-me', 600);
await p.evaluate(() => window.__lt.go('studio', {}, { replace: true })); await shot('13-studio', 600);
await p.evaluate(() => window.__lt.go('camera', {})); await shot('14-camera', 1800);
const gal = '/home/user/LittleTales/assets/photos/skyline-dusk.jpg';
await p.setInputFiles('input[type=file]:not([capture])', gal); await shot('15-thought', 900);
await p.fill('.thought-input', 'Slow coffee before the day got loud.'); await shot('15b-thought-filled', 300);
await p.click('text=Next'); await shot('16-frame', 800);
await p.fill('.title-input', 'A calm morning'); await p.click('.chip.lt-golden'); await shot('16b-frame-golden', 300);
await p.click('text=Stamp it'); await shot('17-stamping', 500);
await p.waitForSelector('.decorate', { timeout: 6000 }); await shot('18-decorate', 900);
await p.click('.tray-item >> nth=0'); await shot('18b-decorate-added', 500);
await p.click('text=Done decorating'); await p.waitForSelector('.ready'); await shot('19-ready', 800);
await p.click('text=Post to my calendar'); await shot('20-celebrate', 1500);
await p.click('.celebrate .link'); await p.waitForTimeout(400);
await p.evaluate(() => window.__lt.go('paywall', { from: 'account' })); await shot('21-paywall', 700);
await p.evaluate(() => { window.__lt.go('checkout', { plan: 'yearly' }); }); await shot('22-checkout', 500);
await p.evaluate(() => window.__lt.go('success', { plan: 'yearly' })); await shot('23-success', 900);
await p.evaluate(async () => { await window.__lt.jumpTo('locked'); window.__lt.go('locked', {}, { replace: true }); }); await shot('24-locked', 700);
await b.close();
console.log(errs.length ? 'page errors: ' + errs.length : 'screens captured');
